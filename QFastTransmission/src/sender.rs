use crate::{
    Action, Body, Config, Error, Feedback, Frame, Pacer, Status, Vector, FLIGHT_CAPACITY,
    HISTORY_CAPACITY, MAX_TOTAL, WIRE_BYTES,
};
use core::fmt;

/// Permission granted by the underlying congestion-controlled transport.
/// Cancellation uses application reserve, but NEVER bypasses this permission.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct SendBudget {
    /// Bytes immediately writable to the underlying transport without blocking.
    pub writable_bytes: usize,
    /// Whether underlying congestion control currently allows transmitting a datagram.
    pub congestion_permitted: bool,
}
impl SendBudget {
    /// Unconstrained per-call budget sufficient for transmitting one `QFT2` frame.
    pub const AVAILABLE: Self = Self {
        writable_bytes: WIRE_BYTES,
        congestion_permitted: true,
    };
}
/// Terminal outcome of a fenced [`Action`] emitted after acknowledgement or post-close query.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Outcome {
    /// Action callback succeeded on the receiver under its exact required prefix.
    Committed(u32),
    /// Evidence is exhausted or the executor reported a partial failure. Never auto-replay.
    Uncertain(u32),
    /// The operation callback was never invoked. Its prefix motion may have executed.
    NotExecuted(u32),
}
impl fmt::Display for Outcome {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Committed(id) => write!(f, "Committed(action #{id})"),
            Self::Uncertain(id) => write!(f, "Uncertain(action #{id})"),
            Self::NotExecuted(id) => write!(f, "NotExecuted(action #{id})"),
        }
    }
}
/// Cumulative diagnostic counters exposed read-only by [`Sender::stats`].
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct SenderStats {
    /// Total nonzero additive input samples accepted by `offer` / `offer_at`.
    pub offers: u64,
    /// Accepted versions folded on the wire by sending a newer cumulative checkpoint.
    pub coalesced: u64,
    /// Total outbound `QFT2` frames generated by `poll`.
    pub sent: u64,
    /// Outbound transmissions that resent a previously transmitted checkpoint, action, or renewal.
    pub retries: u64,
    /// Accepted input samples discarded because `motion_ttl_ms` or lease expiry closed the channel.
    pub expired_offers: u64,
    /// Samples rejected by experimental `predictive_admission` before expiration.
    pub admission_denied: u64,
    /// Peak concurrent in-flight attempt slots occupied during this sender's lifetime.
    pub peak_tracked: usize,
    /// Actions definitively resolved (`Committed` or `NotExecuted`) after effect closure.
    pub reconciled: u64,
    /// Samples sharing an unsent history record; distinct from wire coalescing.
    pub history_merges: u64,
}
#[derive(Clone, Copy, Debug, Default)]
struct Input {
    version: u32,
    count: u32,
    at: u64,
}
#[derive(Clone, Copy, Debug)]
struct Attempt {
    serial: u32,
    body: Body,
    at: u64,
}
#[derive(Clone, Copy, Debug)]
struct Pending {
    body: Body,
    born: u64,
    last_sent: Option<u64>,
}

/// Sender state machine managing cumulative motion history, fenced actions,
/// receiver lease bounds, post-close result observation, and pacing.
#[derive(Debug)]
pub struct Sender {
    config: Config,
    session: u64,
    lease: u32,
    deadline: u64,
    clock: u64,
    last_capture: u64,
    version: u32,
    highest_sent: u32,
    total: Vector,
    last_action: u32,
    serial: u32,
    history: [Input; HISTORY_CAPACITY],
    history_len: usize,
    attempts: [Option<Attempt>; FLIGHT_CAPACITY],
    action: Option<Pending>,
    renewal: Option<Pending>,
    cancel_sent: Option<Attempt>,
    cancel_confirmed: bool,
    cancel_attempts: u8,
    closed: bool,
    retired_action: Option<Body>,
    resolution_until: Option<u64>,
    action_first: u32,
    action_last: u32,
    renewal_first: u32,
    renewal_last: u32,
    cancel_first: u32,
    probe_last: u32,
    outcome: Option<Outcome>,
    pacer: Pacer,
    stats: SenderStats,
}
impl Sender {
    /// `request_started_us` is the local start of the authenticated grant request.
    /// Since minting follows that request, start+TTL is a conservative local bound.
    /// Never replace it with grant-arrival+TTL: that would extend the receiver lease.
    pub fn new(
        grant: Frame,
        request_started_us: u64,
        now_us: u64,
        config: Config,
    ) -> Result<Self, Error> {
        let config = config.validate()?;
        let Body::Grant { ttl_ms } = grant.body else {
            return Err(Error::InvalidFrame);
        };
        if grant.session == 0 || grant.lease == 0 || ttl_ms != config.lease_ms {
            return Err(Error::InvalidConfig);
        }
        let deadline = request_started_us
            .checked_add(ttl_ms as u64 * 1000)
            .ok_or(Error::Range)?;
        if now_us < request_started_us {
            return Err(Error::ClockReversed);
        }
        if now_us >= deadline {
            return Err(Error::Expired);
        }
        Ok(Self {
            config,
            session: grant.session,
            lease: grant.lease,
            deadline,
            clock: now_us,
            last_capture: now_us,
            version: 0,
            highest_sent: 0,
            total: Vector::ZERO,
            last_action: 0,
            serial: 0,
            history: [Input::default(); HISTORY_CAPACITY],
            history_len: 0,
            attempts: [None; FLIGHT_CAPACITY],
            action: None,
            renewal: None,
            cancel_sent: None,
            cancel_confirmed: false,
            cancel_attempts: 0,
            closed: false,
            retired_action: None,
            resolution_until: None,
            action_first: 0,
            action_last: 0,
            renewal_first: 0,
            renewal_last: 0,
            cancel_first: 0,
            probe_last: 0,
            outcome: None,
            pacer: Pacer::new(config.base_interval_us, now_us),
            stats: SenderStats::default(),
        })
    }
    fn advance(&mut self, now_us: u64) -> Result<(), Error> {
        if now_us < self.clock {
            return Err(Error::ClockReversed);
        }
        self.clock = now_us;
        if !self.closed {
            let mut cutoff = self.deadline;
            if self.history_len > 0 {
                cutoff = cutoff.min(
                    self.history[0]
                        .at
                        .saturating_add(self.config.motion_ttl_ms as u64 * 1000),
                );
            }
            if let Some(action) = self.action {
                cutoff = cutoff.min(
                    action
                        .born
                        .saturating_add(self.config.action_ttl_ms as u64 * 1000),
                );
            }
            if now_us >= cutoff {
                self.stats.expired_offers += self.pending_inputs() as u64;
                self.stop(cutoff);
            }
        }
        if self.resolution_until.is_some_and(|until| now_us >= until) {
            if let Some(Body::Action { id, .. }) = self.retired_action {
                self.outcome = Some(Outcome::Uncertain(id));
            }
            self.resolution_until = None;
        }
        Ok(())
    }
    fn stop(&mut self, at: u64) {
        if self.closed {
            return;
        }
        if let Some(Pending {
            body: body @ Body::Action { id, .. },
            ..
        }) = self.action
        {
            self.retired_action = Some(body);
            if self.action_first == 0 {
                self.outcome = Some(Outcome::NotExecuted(id));
            } else if self.config.confirmation_grace_ms == 0 {
                self.outcome = Some(Outcome::Uncertain(id));
            } else {
                self.resolution_until =
                    Some(at.saturating_add(self.config.confirmation_grace_ms as u64 * 1000));
            }
        }
        self.action = None;
        self.renewal = None;
        self.closed = true;
        self.history_len = 0;
        self.attempts = [None; FLIGHT_CAPACITY];
    }
    /// Effect transmission is closed; result-only observation can remain active.
    #[must_use]
    pub fn awaiting_confirmation(&self) -> bool {
        self.resolution_until.is_some()
    }
    /// Return the deadline (in microseconds) when bounded post-close result observation ends.
    #[must_use]
    pub fn confirmation_deadline(&self) -> Option<u64> {
        self.resolution_until
    }
    /// Return `true` if the effect channel is closed and will reject new motion or actions.
    #[must_use]
    pub fn is_closed(&self) -> bool {
        self.closed
    }
    /// Return the authenticated session identifier bound to this sender.
    #[must_use]
    pub fn session(&self) -> u64 {
        self.session
    }
    /// Return the currently active lease generation.
    #[must_use]
    pub fn lease(&self) -> u32 {
        self.lease
    }
    /// Return the highest local checkpoint version offered in the active lease.
    #[must_use]
    pub fn current_version(&self) -> u32 {
        self.version
    }
    /// Return the cumulative coordinate vector associated with `current_version`.
    #[must_use]
    pub fn current_total(&self) -> Vector {
        self.total
    }
    /// Return the highest action identifier queued in the active lease.
    #[must_use]
    pub fn last_action_id(&self) -> u32 {
        self.last_action
    }
    /// Return the pending fenced action currently blocking subsequent motion, if any.
    #[must_use]
    pub fn pending_action(&self) -> Option<Action> {
        match self.action {
            Some(Pending {
                body: Body::Action { action, .. },
                ..
            }) => Some(action),
            _ => None,
        }
    }
    /// Return `true` when an unacknowledged fenced action is active.
    #[must_use]
    pub fn has_pending_action(&self) -> bool {
        self.action.is_some()
    }
    /// Return `true` when a lease renewal handshake is awaiting its matching grant.
    #[must_use]
    pub fn is_renewing(&self) -> bool {
        self.renewal.is_some()
    }
    /// Return `true` if calling `begin_renewal` is valid right now (open lease, no pending action/renewal/outcome).
    #[must_use]
    pub fn can_begin_renewal(&self) -> bool {
        !self.closed
            && self.action.is_none()
            && self.renewal.is_none()
            && self.outcome.is_none()
            && self.lease < u32::MAX
    }
    /// Return the validated configuration governing this sender.
    #[must_use]
    pub fn config(&self) -> Config {
        self.config
    }
    /// Notify the adaptive pacer that the underlying network path switched (for
    /// example Wi-Fi to cellular handoff), dropping stale RTT/baseline estimates
    /// while preserving lease state, coordinates, and rate-limit token buckets.
    pub fn reset_path(&mut self, now_us: u64) -> Result<(), Error> {
        self.advance(now_us)?;
        self.pacer.reset_path(now_us)
    }
    /// Return cumulative sender statistics snapshot.
    #[must_use]
    pub fn stats(&self) -> SenderStats {
        self.stats
    }
    /// Change the base send interval without replacing the lease or pending inputs.
    pub fn set_base_interval_us(&mut self, interval: u32) -> Result<(), Error> {
        if !(1_000..=64_000).contains(&interval) {
            return Err(Error::InvalidConfig);
        }
        self.config.base_interval_us = interval;
        self.pacer.set_base_interval(interval);
        Ok(())
    }

    /// Return read-only telemetry from the internal [`Pacer`].
    #[must_use]
    pub fn pacing(&self) -> crate::PacerMetrics {
        self.pacer.metrics()
    }
    /// Return `true` once the receiver has acknowledged lease closure (`Cancelled` / probe result).
    #[must_use]
    pub fn cancellation_confirmed(&self) -> bool {
        self.cancel_confirmed
    }
    /// Return the current local upper-bound deadline (in microseconds) of this lease.
    #[must_use]
    pub fn expires_at(&self) -> u64 {
        self.deadline
    }
    /// Return the count of currently tracked in-flight attempt slots (`0..=max_in_flight`).
    #[must_use]
    pub fn tracked(&self) -> usize {
        self.attempts.iter().flatten().count()
    }
    /// Accepted nonzero samples awaiting prefix confirmation. May exceed
    /// HISTORY_CAPACITY; use `history_records` to measure bounded storage.
    #[must_use]
    pub fn pending_inputs(&self) -> usize {
        self.history[..self.history_len]
            .iter()
            .map(|input| input.count as usize)
            .sum()
    }
    /// Storage records, separate from the number of accepted samples awaiting ACK.
    #[must_use]
    pub fn history_records(&self) -> usize {
        self.history_len
    }
    /// Consume and return the latest terminal [`Outcome`], clearing the busy outcome fence.
    #[must_use]
    pub fn take_outcome(&mut self) -> Option<Outcome> {
        self.outcome.take()
    }
    /// Immediately close the sender effect channel and transition to cancellation/observation.
    pub fn cancel(&mut self, now_us: u64) -> Result<(), Error> {
        self.advance(now_us)?;
        self.stop(now_us);
        Ok(())
    }
    /// Call after a transport write fails; a partial write cannot be safely replayed.
    pub fn transport_failed(&mut self, now_us: u64) -> Result<(), Error> {
        self.cancel(now_us)
    }
    /// Offer an additive coordinate delta captured at `now_us`.
    pub fn offer(&mut self, delta: Vector, now_us: u64) -> Result<(), Error> {
        self.offer_at(delta, now_us, now_us)
    }
    /// Preserve application capture time across local queues. Times share this
    /// sender's monotonic clock and must be nondecreasing in input order.
    /// An already-expired input closes the effect path instead of gaining a new TTL.
    pub fn offer_at(&mut self, delta: Vector, captured_us: u64, now_us: u64) -> Result<(), Error> {
        self.advance(now_us)?;
        if self.closed {
            return Err(Error::Expired);
        }
        if self.action.is_some() || self.renewal.is_some() {
            return Err(Error::Busy);
        }
        if captured_us < self.last_capture || captured_us > now_us {
            return Err(Error::InvalidTimestamp);
        }
        if delta == Vector::ZERO {
            return Ok(());
        }
        let cutoff = captured_us.saturating_add(self.config.motion_ttl_ms as u64 * 1000);
        if now_us >= cutoff {
            self.stop(cutoff);
            return Err(Error::Expired);
        }
        let merge = self.config.compact_history
            && self.history_len > 0
            && self.history[self.history_len - 1].version > self.highest_sent;
        if !merge && self.history_len == HISTORY_CAPACITY {
            return Err(Error::Capacity);
        }
        let total = self.total.checked_add(delta).ok_or(Error::Range)?;
        if !delta.bounded(self.config.max_catchup) || !total.bounded(MAX_TOTAL) {
            return Err(Error::Range);
        }
        let version = self
            .version
            .checked_add(1)
            .ok_or(Error::SequenceExhausted)?;
        self.version = version;
        self.total = total;
        self.last_capture = captured_us;
        if merge {
            let input = &mut self.history[self.history_len - 1];
            input.version = version;
            input.count += 1;
            self.stats.history_merges += 1;
        } else {
            self.history[self.history_len] = Input {
                version,
                count: 1,
                at: captured_us,
            };
            self.history_len += 1;
        }
        self.stats.offers += 1;
        Ok(())
    }
    /// Freezes subsequent motion until this operation is terminally acknowledged.
    /// The operation carries the exact cumulative prefix, so lost motion packets
    /// need not be individually retransmitted before executing the operation.
    pub fn queue_action(&mut self, action: Action, now_us: u64) -> Result<u32, Error> {
        self.queue_action_at(action, now_us, now_us)
    }
    /// Capture-aware action admission. Capture time cannot precede the current prefix.
    pub fn queue_action_at(
        &mut self,
        action: Action,
        captured_us: u64,
        now_us: u64,
    ) -> Result<u32, Error> {
        self.queue_step_at(Vector::ZERO, captured_us, action, captured_us, now_us)
    }
    /// Admit a pending additive delta and its dependent action as a single local step.
    /// Both capture times use the sender's monotonic clock. An error admits neither
    /// part; advancing time can still expire earlier work and close the lease.
    /// A successful step uses one ordinary QFT2 action fence. Wait for its matching
    /// committed outcome before submitting the next dependent step. Receiver-side
    /// motion may already have taken effect if the action subsequently fails.
    pub fn queue_step_at(
        &mut self,
        delta: Vector,
        delta_captured_us: u64,
        action: Action,
        captured_us: u64,
        now_us: u64,
    ) -> Result<u32, Error> {
        self.advance(now_us)?;
        if self.closed {
            return Err(Error::Expired);
        }
        if self.action.is_some() || self.renewal.is_some() || self.outcome.is_some() {
            return Err(Error::Busy);
        }
        if delta_captured_us < self.last_capture
            || delta_captured_us > captured_us
            || captured_us > now_us
        {
            return Err(Error::InvalidTimestamp);
        }
        let cutoff = captured_us.saturating_add(self.config.action_ttl_ms as u64 * 1000);
        if now_us >= cutoff {
            self.stop(cutoff);
            return Err(Error::Expired);
        }
        let id = self
            .last_action
            .checked_add(1)
            .ok_or(Error::SequenceExhausted)?;
        // All fallible action checks are complete before changing the cumulative prefix.
        if delta != Vector::ZERO {
            self.offer_at(delta, delta_captured_us, now_us)?;
        }
        self.last_action = id;
        self.last_capture = captured_us;
        self.action_first = 0;
        self.action_last = 0;
        self.action = Some(Pending {
            body: Body::Action {
                id,
                version: self.version,
                total: self.total,
                action,
            },
            born: captured_us,
            last_sent: None,
        });
        Ok(id)
    }
    /// Request a new lease with the current cumulative position, including unconfirmed motion.
    /// A pending action, renewal, or unconsumed outcome blocks the request.
    pub fn begin_renewal(&mut self, now_us: u64) -> Result<(), Error> {
        self.advance(now_us)?;
        if self.closed {
            return Err(Error::Expired);
        }
        if self.action.is_some() || self.renewal.is_some() || self.outcome.is_some() {
            return Err(Error::Busy);
        }
        if self.lease == u32::MAX {
            return Err(Error::SequenceExhausted);
        }
        self.renewal_first = 0;
        self.renewal_last = 0;
        self.renewal = Some(Pending {
            body: Body::Renew {
                version: self.version,
                last_action: self.last_action,
                total: self.total,
            },
            born: now_us,
            last_sent: None,
        });
        Ok(())
    }
    fn make(&mut self, body: Body, now_us: u64, track: bool) -> Result<Frame, Error> {
        let serial = self.serial.checked_add(1).ok_or(Error::SequenceExhausted)?;
        let frame = Frame {
            session: self.session,
            lease: self.lease,
            serial,
            body,
        };
        if track {
            let slot = self
                .attempts
                .iter_mut()
                .find(|v| v.is_none())
                .ok_or(Error::Capacity)?;
            *slot = Some(Attempt {
                serial,
                body,
                at: now_us,
            });
        }
        self.serial = serial;
        self.stats.sent += 1;
        self.stats.peak_tracked = self.stats.peak_tracked.max(self.tracked());
        Ok(frame)
    }
    /// Earliest useful timer, assuming no new input, ACK, configuration or transport
    /// event. Recompute on those events. A blocked transport suppresses write timers,
    /// never expiry/observation deadlines. `None` means await an external event.
    /// This does not mutate state; call `poll` at the returned time.
    pub fn next_poll_at(&self, now_us: u64, budget: SendBudget) -> Result<Option<u64>, Error> {
        if now_us < self.clock {
            return Err(Error::ClockReversed);
        }
        let mut deadline = if self.closed {
            self.resolution_until
        } else {
            let mut at = self.deadline;
            if self.history_len > 0 {
                at = at.min(
                    self.history[0]
                        .at
                        .saturating_add(self.config.motion_ttl_ms as u64 * 1000),
                );
            }
            if let Some(action) = self.action {
                at = at.min(
                    action
                        .born
                        .saturating_add(self.config.action_ttl_ms as u64 * 1000),
                );
            }
            Some(at)
        };
        if !budget.congestion_permitted || budget.writable_bytes < WIRE_BYTES {
            return Ok(deadline.map(|at| at.max(now_us)));
        }
        let retry = self.pacer.retry_us() as u64;
        if !self.closed {
            // Retiring a timestamp also changes which delayed ACKs may supply RTT
            // feedback, so this maintenance must not depend on polling frequency.
            if let Some(expiry) = self
                .attempts
                .iter()
                .flatten()
                .filter_map(|a| a.at.checked_add(retry))
                .min()
            {
                deadline = Some(deadline.unwrap_or(expiry).min(expiry));
            }
        }
        let send_at = if self.closed {
            if self.cancel_confirmed || self.cancel_attempts >= 8 {
                None
            } else {
                self.cancel_sent
                    .map_or(Some(now_us), |a| a.at.checked_add(retry))
                    .and_then(|at| {
                        self.pacer
                            .next_permit_at(now_us, true)
                            .map(|pace| at.max(pace))
                    })
            }
        } else {
            if self.config.predictive_admission && self.history_len > 0 {
                let predicted = self.history[0]
                    .at
                    .saturating_add(self.config.motion_ttl_ms as u64 * 1000)
                    .saturating_sub(self.pacer.estimated_arrival_us() as u64);
                deadline = Some(deadline.unwrap_or(predicted).min(predicted));
            }
            let work_at = if let Some(pending) = self.renewal.or(self.action) {
                pending
                    .last_sent
                    .map_or(Some(now_us), |at| at.checked_add(retry))
            } else if self.history_len > 0 {
                self.attempts
                    .iter()
                    .flatten()
                    .filter(
                        |a| matches!(a.body,Body::Checkpoint {version,..} if version==self.version),
                    )
                    .try_fold(now_us, |latest, a| {
                        a.at.checked_add(retry).map(|at| latest.max(at))
                    })
            } else {
                None
            };
            work_at.and_then(|mut at| {
                // Slots already expired at now will be reclaimed by poll.
                let live = self
                    .attempts
                    .iter()
                    .flatten()
                    .filter(|a| now_us.saturating_sub(a.at) < retry);
                if live.clone().count() >= self.config.max_in_flight as usize {
                    at = at.max(live.filter_map(|a| a.at.checked_add(retry)).min()?);
                }
                Some(at.max(self.pacer.next_permit_at(now_us, false)?))
            })
        };
        Ok(match (deadline, send_at) {
            (Some(a), Some(b)) => Some(a.min(b).max(now_us)),
            (Some(a), None) | (None, Some(a)) => Some(a.max(now_us)),
            (None, None) => None,
        })
    }
    /// Produce at most one datagram/message. Clocks and send permission come from
    /// the adapter. Attempts are bounded bookkeeping, not an estimate of bytes
    /// still in the network; the underlying transport remains responsible for CC.
    pub fn poll(&mut self, now_us: u64, budget: SendBudget) -> Result<Option<Frame>, Error> {
        self.advance(now_us)?;
        if !budget.congestion_permitted || budget.writable_bytes < WIRE_BYTES {
            return Ok(None);
        }
        let retry = self.pacer.retry_us() as u64;
        for attempt in &mut self.attempts {
            if attempt.is_some_and(|a| now_us.saturating_sub(a.at) >= retry) {
                *attempt = None;
            }
        }
        if !self.closed && self.config.predictive_admission && self.history_len > 0 {
            let remaining = self.history[0]
                .at
                .saturating_add(self.config.motion_ttl_ms as u64 * 1000)
                .saturating_sub(now_us);
            if remaining <= self.pacer.estimated_arrival_us() as u64 {
                self.stats.admission_denied += self.pending_inputs() as u64;
                self.stop(now_us);
            }
        }
        if self.closed {
            if self.cancel_confirmed
                || self.cancel_attempts >= 8
                || self
                    .cancel_sent
                    .is_some_and(|a| now_us.saturating_sub(a.at) < retry)
                || !self.pacer.permit(now_us, true)
            {
                return Ok(None);
            }
            let body = match (self.resolution_until, self.retired_action) {
                (
                    Some(_),
                    Some(Body::Action {
                        id,
                        version,
                        total,
                        action,
                    }),
                ) => Body::CancelAction {
                    id,
                    version,
                    total,
                    action,
                },
                _ => Body::Cancel,
            };
            let frame = self.make(body, now_us, false)?;
            if self.cancel_first == 0 {
                self.cancel_first = frame.serial;
            }
            if matches!(body, Body::CancelAction { .. }) {
                self.probe_last = frame.serial;
            }
            self.cancel_sent = Some(Attempt {
                serial: frame.serial,
                body,
                at: now_us,
            });
            self.cancel_attempts += 1;
            return Ok(Some(frame));
        }
        if self.tracked() >= self.config.max_in_flight as usize {
            return Ok(None);
        }
        let pending = self.renewal.or(self.action);
        let body = if let Some(pending) = pending {
            if pending
                .last_sent
                .is_some_and(|at| now_us.saturating_sub(at) < retry)
            {
                return Ok(None);
            }
            pending.body
        } else {
            if self.history_len == 0
                || self.attempts.iter().flatten().any(|a| {
                    matches!(a.body, Body::Checkpoint { version, .. } if version == self.version)
                })
            {
                return Ok(None);
            }
            Body::Checkpoint {
                version: self.version,
                total: self.total,
            }
        };
        // Renewals bypass the pacing slot reserved for motion checkpoints.
        let urgent = matches!(body, Body::Renew { .. });
        if !self.pacer.permit(now_us, urgent) {
            return Ok(None);
        }
        let frame = self.make(body, now_us, true)?;
        if matches!(body, Body::Renew { .. }) {
            if self.renewal_first == 0 {
                self.renewal_first = frame.serial;
            }
            self.renewal_last = frame.serial;
        }
        if matches!(body, Body::Action { .. }) {
            if self.action_first == 0 {
                self.action_first = frame.serial;
            }
            self.action_last = frame.serial;
        }
        if let Some(pending) = self.renewal.as_mut().or(self.action.as_mut()) {
            if pending.last_sent.is_some() {
                self.stats.retries += 1;
            }
            pending.last_sent = Some(now_us);
        }
        if let Body::Checkpoint { version, .. } | Body::Action { version, .. } = body {
            self.stats.coalesced +=
                version.saturating_sub(self.highest_sent.saturating_add(1)) as u64;
            if version == self.highest_sent && matches!(body, Body::Checkpoint { .. }) {
                self.stats.retries += 1;
            }
            self.highest_sent = self.highest_sent.max(version);
        }
        Ok(Some(frame))
    }
    /// Process an inbound `Ack` or renewal `Grant` arriving at monotonic timestamp `now_us`.
    pub fn receive(&mut self, frame: Frame, now_us: u64) -> Result<(), Error> {
        if frame.session != self.session {
            return Err(Error::WrongSession);
        }
        self.advance(now_us)?;
        if let Body::Grant { ttl_ms } = frame.body {
            if frame.lease == self.lease {
                return Ok(());
            } // duplicate grant must not reset state
            let Some(renewal) = self.renewal else {
                return Err(Error::WrongLease);
            };
            if self.closed
                || self.lease.checked_add(1) != Some(frame.lease)
                || ttl_ms != self.config.lease_ms
            {
                return Err(Error::WrongLease);
            }
            let deadline = renewal
                .born
                .checked_add(ttl_ms as u64 * 1000)
                .ok_or(Error::Range)?;
            if now_us >= deadline {
                self.stop(now_us);
                return Err(Error::Expired);
            }
            // The renewal serial range still identifies grants after their RTT slots expire.
            if self.renewal_first == 0
                || frame.serial < self.renewal_first
                || frame.serial > self.renewal_last
            {
                return Err(Error::Unconfirmed);
            }
            self.lease = frame.lease;
            self.deadline = deadline;
            self.version = 0;
            self.highest_sent = 0;
            self.last_action = 0;
            self.last_capture = now_us;
            self.attempts = [None; FLIGHT_CAPACITY];
            self.history_len = 0;
            self.renewal = None;
            self.renewal_first = 0;
            self.renewal_last = 0;
            return Ok(());
        }
        if frame.lease != self.lease {
            return Err(Error::WrongLease);
        }
        let Body::Ack {
            version,
            action_id,
            status,
            queue_us,
        } = frame.body
        else {
            return Err(Error::InvalidFrame);
        };
        if self.closed {
            let cancellation = self.cancel_sent.is_some_and(|last| {
                self.cancel_first <= frame.serial && frame.serial <= last.serial
            });
            let probe = cancellation && frame.serial <= self.probe_last;
            if cancellation && !probe && action_id == 0 && status == Status::Cancelled {
                self.cancel_confirmed = true;
            }
            if let Some(Body::Action {
                id, version: sent, ..
            }) = self.retired_action
            {
                let action_ack = self.action_first != 0
                    && self.action_first <= frame.serial
                    && frame.serial <= self.action_last;
                if (probe || action_ack) && action_id == id {
                    if (status == Status::Committed && version != sent)
                        || version > self.highest_sent
                    {
                        return Err(Error::Conflict);
                    }
                    if probe
                        && matches!(
                            status,
                            Status::Committed | Status::Cancelled | Status::ExecutionUncertain
                        )
                    {
                        self.cancel_confirmed = true;
                    }
                    if self.resolution_until.is_some() {
                        let result = match status {
                            Status::Committed => Some(Outcome::Committed(id)),
                            Status::Cancelled if probe => Some(Outcome::NotExecuted(id)),
                            Status::ExecutionUncertain => Some(Outcome::Uncertain(id)),
                            _ => None,
                        };
                        if let Some(result) = result {
                            self.outcome = Some(result);
                            self.resolution_until = None;
                            self.stats.reconciled +=
                                u64::from(!matches!(result, Outcome::Uncertain(_)));
                        }
                    }
                }
            }
            return Ok(()); // Closing never reopens the effect path.
        }
        let tracked_attempt = self
            .attempts
            .iter()
            .flatten()
            .find(|a| a.serial == frame.serial)
            .copied();
        // Stable action identity outlives an individual RTT bookkeeping slot.
        // Action retries occupy a contiguous serial range while input is frozen.
        let sent_body = if let Some(attempt) = tracked_attempt {
            attempt.body
        } else if self.action_first != 0
            && self.action_first <= frame.serial
            && frame.serial <= self.action_last
        {
            if let Some(action) = self.action {
                action.body
            } else {
                return Ok(());
            }
        } else {
            return Ok(());
        };
        if version > self.highest_sent {
            return Err(Error::Conflict);
        }
        let valid = match sent_body {
            Body::Checkpoint { version: sent, .. } => {
                action_id == 0
                    && status != Status::Committed
                    && (status != Status::Applied || version >= sent)
            }
            Body::Action {
                id, version: sent, ..
            } => {
                (action_id == id || status == Status::Expired)
                    && (status != Status::Committed || version >= sent)
            }
            Body::Renew { .. } => status == Status::Expired,
            _ => false,
        };
        if !valid {
            return Err(Error::Conflict);
        }
        if let Some(attempt) = tracked_attempt {
            self.pacer.observe_with_adaptation(
                Feedback {
                    rtt_us: now_us.saturating_sub(attempt.at).min(u32::MAX as u64) as u32,
                    queue_us,
                },
                now_us,
                self.config.adaptive_pacing,
            );
        }
        for slot in &mut self.attempts {
            if slot.is_some_and(|a| {
                a.serial == frame.serial
                    || matches!(a.body, Body::Checkpoint {version:v,..} if v <= version)
            }) {
                *slot = None;
            }
        }
        if matches!(status, Status::Applied | Status::Committed | Status::Stale) {
            let consumed = self.history[..self.history_len]
                .iter()
                .take_while(|input| input.version <= version)
                .count();
            self.history.copy_within(consumed..self.history_len, 0);
            self.history_len -= consumed;
        }
        if let Some(Pending {
            body: Body::Action { id, .. },
            ..
        }) = self.action
        {
            if action_id == id && matches!(sent_body, Body::Action { .. }) {
                if status == Status::Committed {
                    self.outcome = Some(Outcome::Committed(id));
                    self.action = None;
                    for slot in &mut self.attempts {
                        if slot.is_some_and(
                            |a| matches!(a.body,Body::Action {id:other,..} if other == id),
                        ) {
                            *slot = None;
                        }
                    }
                } else {
                    self.stop(now_us);
                }
            }
        }
        if matches!(
            status,
            Status::Expired | Status::Conflict | Status::ExecutionUncertain | Status::Rejected
        ) {
            self.stop(now_us);
        }
        Ok(())
    }
}
